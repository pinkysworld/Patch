#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const paperDir = path.join(root, 'paper');
const mainPath = path.join(paperDir, 'main.tex');
const abstractPath = path.join(paperDir, 'submission-abstract.tex');
const disclosurePath = path.join(paperDir, 'submission-disclosure.tex');
const outPath = path.join(paperDir, 'main-submission-body.tex');

const main = fs.readFileSync(mainPath, 'utf8');
const journalAbstract = fs.readFileSync(abstractPath, 'utf8').trim();
const disclosure = fs.readFileSync(disclosurePath, 'utf8').trim();

function fail(message) {
  console.error(`Programming Journal source build failed: ${message}`);
  process.exit(1);
}

const bodyStart = main.indexOf('\\begin{document}');
const bodyEnd = main.lastIndexOf('\\end{document}');
if (bodyStart < 0 || bodyEnd < 0 || bodyEnd <= bodyStart) {
  fail('canonical main.tex does not contain one usable document body');
}

let body = main.slice(bodyStart + '\\begin{document}'.length, bodyEnd).trim();

const abstractMatches = [...body.matchAll(/\\begin\{abstract\}[\s\S]*?\\end\{abstract\}/g)];
if (abstractMatches.length !== 1) fail(`expected one canonical abstract, found ${abstractMatches.length}`);
body = body.replace(
  abstractMatches[0][0],
  `\\begin{abstract}\n${journalAbstract}\n\\end{abstract}`
);

const abstractLabels = ['Context.', 'Inquiry.', 'Approach.', 'Knowledge.', 'Grounding.', 'Importance.'];
for (const label of abstractLabels) {
  if (!journalAbstract.includes(`\\textbf{${label}}`)) fail(`submission abstract is missing ${label}`);
}
if (/\\cite\{|\\ref\{|\$|\\\[|\\\(/.test(journalAbstract)) {
  fail('submission abstract must remain citation-free and free of mathematical notation');
}
const abstractWords = journalAbstract
  .replace(/\\textbf\{[^}]+\}/g, ' ')
  .replace(/\\[A-Za-z]+\{([^}]*)\}/g, '$1')
  .replace(/[^A-Za-z0-9'-]+/g, ' ')
  .trim()
  .split(/\s+/)
  .filter(Boolean).length;
if (abstractWords > 500) fail(`submission abstract has ${abstractWords} words; journal limit is 500`);

const keywordPattern = /\n\\noindent\\textbf\{Keywords:\}[^\n]*\n/;
if (!keywordPattern.test(body)) fail('canonical article keyword line was not found');
body = body.replace(keywordPattern, '\n');

const copyedits = [
  ['This manuscript makes four scoped contributions', 'The manuscript makes four scoped contributions'],
  ['The main limitations are now concentrated here.', 'The main limitations are as follows.'],
  ['These extensions would deepen evidence but are not silently inferred from the current artifact.', 'These extensions would strengthen the evidence but are outside the claims supported by the current artifact.'],
];
for (const [from, to] of copyedits) {
  if (!body.includes(from)) fail(`copyediting anchor drifted: ${from}`);
  body = body.replace(from, to);
}

const appendixMarker = '\\appendix';
if (!body.includes(appendixMarker)) fail('appendix marker not found');
body = body.replace(appendixMarker, `${disclosure}\n\n${appendixMarker}`);

fs.writeFileSync(
  outPath,
  `% Generated from paper/main.tex by scripts/build-programming-submission-source.js.\n% Do not edit this file by hand.\n\n${body}\n`
);
console.log(`Built ${path.relative(root, outPath)} with ${abstractWords}-word journal abstract.`);
